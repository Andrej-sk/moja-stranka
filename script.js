function renderCompare(){
  const a=document.getElementById("a"),b=document.getElementById("b");
  if(!a||!b)return;
  fillSelect("a");fillSelect("b");
  const rows=document.getElementById("rows");
  const fields=[["Cena (orientačne)","price"],["Displej","display"],["Materiál","case"],["Maximálny jas","brightness"],["Čip","chip"],["Úložisko","storage"],["Výdrž batérie","battery"],["Zdravie","health"],["Šport a GPS","activity"],["Bezpečnosť","safety"],["Odolnosť","durability"],["Pripojenie","connectivity"],["Nabíjanie","charging"],["Kompatibilita","compatibility"]];
  function draw(){
    document.getElementById("ha").textContent=a.value;
    document.getElementById("hb").textContent=b.value;
    rows.innerHTML=fields.map(([label,key])=>'<tr><td>'+label+'</td><td>'+models[a.value][key]+'</td><td>'+models[b.value][key]+'</td></tr>').join("");
  }
  a.onchange=draw;b.onchange=draw;draw();
}
